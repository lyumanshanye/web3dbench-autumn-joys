function showHome({ restoreScroll = false, targetId = "", focusHeading = false } = {}) {
  articleView.hidden = true;
  homeView.hidden = false;
  document.body.dataset.view = "home";
  setHomeMeta();
  applyFilter(activeFilter, false);
  hasHomeContext = true;

  afterLayout(() => {
    if (restoreScroll) {
      scrollImmediately(homeScrollPosition);
    } else {
      const target = targetId ? document.getElementById(targetId) : null;
      if (target) {
        const targetTop = target.getBoundingClientRect().top + window.scrollY - 92;
        scrollImmediately(Math.max(0, targetTop));
      }
    }

    if (focusHeading) {
      document.querySelector("#journal-title")?.focus({ preventScroll: true });
    }
  });
}

function showArticle(post, index, slug) {
  if (currentSlug === null) {
    homeScrollPosition = window.scrollY;
  }

  homeView.hidden = true;
  articleView.hidden = false;
  document.body.dataset.view = "article";
  renderArticle(post, index);
  currentSlug = slug;

  scrollImmediately(0);
  afterLayout(() => {
    scrollImmediately(0);
    document.querySelector("#article-title")?.focus({ preventScroll: true });
  });
}

function showMissingArticle() {
  if (currentSlug === null) {
    homeScrollPosition = window.scrollY;
  }

  homeView.hidden = true;
  articleView.hidden = false;
  document.body.dataset.view = "article";
  renderNotFound();
  currentSlug = "__not-found__";

  scrollImmediately(0);
  afterLayout(() => {
    scrollImmediately(0);
    document.querySelector("#article-title")?.focus({ preventScroll: true });
  });
}

function afterLayout(callback) {
  window.setTimeout(callback, 0);
}

function scrollImmediately(top) {
  const root = document.documentElement;
  const body = document.body;
  const previousRootBehavior = root.style.scrollBehavior;
  const previousBodyBehavior = body.style.scrollBehavior;
  root.style.scrollBehavior = "auto";
  body.style.scrollBehavior = "auto";
  void root.offsetHeight;
  window.scrollTo({ top, left: 0, behavior: "auto" });
  root.style.scrollBehavior = previousRootBehavior;
  body.style.scrollBehavior = previousBodyBehavior;
}

function articleSlugFromHash() {
  const match = window.location.hash.match(/^#\/journal\/([^/?#]+)\/?$/);
  if (!match) return null;
  try {
    return decodeURIComponent(match[1]);
  } catch {
    return match[1];
  }
}

function handleRoute() {
  const slug = articleSlugFromHash();

  if (slug) {
    const index = POSTS.findIndex((post) => post.slug === slug);
    if (index >= 0) {
      showArticle(POSTS[index], index, slug);
    } else {
      showMissingArticle();
    }
    return;
  }

  const returningFromArticle = currentSlug !== null;
  currentSlug = null;

  const hashTarget = window.location.hash.replace(/^#/, "");
  const shouldRestore =
    returningFromArticle &&
    hasHomeContext &&
    (hashTarget === "" || hashTarget === "journal");

  showHome({
    restoreScroll: shouldRestore,
    targetId: hashTarget,
    focusHeading:
      returningFromArticle && (hashTarget === "" || hashTarget === "journal"),
  });
}

function rememberScrollBeforeArticle(event) {
  if (currentSlug !== null || !(event.target instanceof Element)) return;
  const link = event.target.closest("a[data-post-link]");
  if (!link) return;
  if (event.metaKey || event.ctrlKey || event.shiftKey || event.altKey) return;
  hasHomeContext = true;
  homeScrollPosition = window.scrollY;
}

