function applyFilter(filter, announce = true) {
  if (!TOPIC_NAMES[filter]) return;

  activeFilter = filter;
  let visibleCount = 0;

  postGrid.querySelectorAll(".post-card").forEach((card) => {
    const isVisible = filter === "all" || card.dataset.topic === filter;
    card.hidden = !isVisible;
    if (isVisible) visibleCount += 1;
  });

  filterButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.filter === filter));
  });

  if (announce) {
    filterStatus.textContent =
      filter === "all"
        ? `Showing all ${visibleCount} notes`
        : `Showing ${visibleCount} ${visibleCount === 1 ? "note" : "notes"} in ${TOPIC_NAMES[filter]}`;
  }
}

function renderBody(body) {
  return body.map((block) => {
    if (block.type === "h2") {
      return `<h2>${escapeHTML(block.content)}</h2>`;
    }
    if (block.type === "blockquote") {
      return `<blockquote><p>${escapeHTML(block.content)}</p></blockquote>`;
    }
    if (block.type === "ul") {
      return `<ul>${block.items.map((item) => `<li>${escapeHTML(item)}</li>`).join("")}</ul>`;
    }
    return `<p>${escapeHTML(block.content)}</p>`;
  }).join("");
}

function updateMeta(title, description, url = window.location.href) {
  document.title = title;
  if (descriptionMeta) descriptionMeta.content = description;
  if (ogTitleMeta) ogTitleMeta.content = title;
  if (ogDescriptionMeta) ogDescriptionMeta.content = description;

  let canonical = document.querySelector('link[rel="canonical"]');
  if (!canonical) {
    canonical = document.createElement("link");
    canonical.rel = "canonical";
    document.head.append(canonical);
  }
  canonical.href = url.split("#")[0];
}

function setHomeMeta() {
  updateMeta(DEFAULT_TITLE, DEFAULT_DESCRIPTION, window.location.href);
}

