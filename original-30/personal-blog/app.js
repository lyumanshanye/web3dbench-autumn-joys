function escapeHTML(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function postURL(post) {
  const url = new URL(window.location.href);
  url.search = "";
  url.hash = `#/journal/${post.slug}`;
  return url.href;
}

