function routePath() {
  const hash = window.location.hash;
  if (!hash || hash === "#" || hash === "#/") return "/";
  const path = hash.startsWith("#") ? hash.slice(1) : hash;
  return path.startsWith("/") ? path : `/${path}`;
}

function saveScrollPosition() {
  if (history.state && typeof history.state.scrollY === "number") {
    history.replaceState({ ...history.state, scrollY: window.scrollY }, "", window.location.href);
  } else {
    history.replaceState({ scrollY: window.scrollY }, "", window.location.href);
  }
}

function jumpToScroll(position) {
  const root = document.documentElement;
  const previousBehavior = root.style.scrollBehavior;
  root.style.scrollBehavior = "auto";
  try {
    window.scrollTo({ top: position, left: 0, behavior: "instant" });
  } catch (error) {
    window.scrollTo(0, position);
  }
  requestAnimationFrame(() => {
    root.style.scrollBehavior = previousBehavior;
  });
}

function navigate(path, options = {}) {
  const currentPath = routePath();
  if (currentPath === path) {
    if (options.section) scrollToSection(options.section);
    return;
  }

  saveScrollPosition();
  history.pushState({ scrollY: 0 }, "", `#${path}`);
  renderRoute({ fromHistory: false, section: options.section });
}

function scrollToSection(sectionId) {
  const target = document.getElementById(sectionId);
  if (!target) return;
  target.scrollIntoView({ behavior: window.matchMedia("(prefers-reduced-motion: reduce)").matches ? "auto" : "smooth", block: "start" });
}

function updateFilters(topic, announce = false) {
  const activeTopic = topicLabels[topic] ? topic : "all";
  let shown = 0;

  document.querySelectorAll(".post-card").forEach((card) => {
    const isVisible = activeTopic === "all" || card.dataset.topic === activeTopic;
    card.hidden = !isVisible;
    if (isVisible) shown += 1;
  });

  filters.forEach((button) => {
    const active = button.dataset.filter === activeTopic;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  postGrid.classList.toggle("is-filtered", activeTopic !== "all");
  visibleCount.textContent = String(shown).padStart(2, "0");

  if (announce) {
    const message = `Showing ${shown} ${shown === 1 ? "note" : "notes"} about ${topicLabels[activeTopic]}.`;
    filterStatus.textContent = message;
  }
}

