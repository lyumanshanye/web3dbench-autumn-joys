function renderRoute({ fromHistory = false, section = null } = {}) {
  const path = routePath();
  const articleMatch = path.match(/^\/notes\/([^/]+)\/?$/);
  const topicMatch = path.match(/^\/topics\/([^/]+)\/?$/);

  if (articleMatch) {
    renderArticle(decodeURIComponent(articleMatch[1]));
    if (fromHistory && history.state && typeof history.state.scrollY === "number") {
      requestAnimationFrame(() => jumpToScroll(history.state.scrollY));
    } else {
      jumpToScroll(0);
    }
  } else if (topicMatch) {
    const topic = decodeURIComponent(topicMatch[1]);
    renderHome(topicLabels[topic] ? topic : "all");
  } else {
    renderHome("all");
    if (section) {
      requestAnimationFrame(() => scrollToSection(section));
    } else if (fromHistory && history.state && typeof history.state.scrollY === "number") {
      requestAnimationFrame(() => jumpToScroll(history.state.scrollY));
    } else if (path !== "/") {
      history.replaceState({ scrollY: 0 }, "", "#/");
    }
  }

  updateProgress();

  if (fromHistory || articleMatch) {
    const heading = articleView.hidden
      ? document.querySelector("#hero-title")
      : document.querySelector("[data-route-heading]");
    if (heading) {
      heading.focus({ preventScroll: true });
    }
  }
}

function updateProgress() {
  if (articleView.hidden) {
    progress.style.transform = "scaleX(0)";
    return;
  }

  const scrollable = document.documentElement.scrollHeight - window.innerHeight;
  const amount = scrollable > 0 ? Math.min(1, Math.max(0, window.scrollY / scrollable)) : 0;
  progress.style.transform = `scaleX(${amount})`;
}

async function copyShareLink(slug, button) {
  const url = `${window.location.origin}${window.location.pathname}#/notes/${slug}`;
  let copied = false;

  try {
    await navigator.clipboard.writeText(url);
    copied = true;
  } catch (error) {
    const temporary = document.createElement("textarea");
    temporary.value = url;
    temporary.setAttribute("readonly", "");
    temporary.style.position = "fixed";
    temporary.style.opacity = "0";
    document.body.appendChild(temporary);
    temporary.select();
    try {
      copied = document.execCommand("copy");
    } catch (fallbackError) {
      copied = false;
    }
    temporary.remove();
  }

  const label = button.querySelector("span");
  if (copied) {
    label.textContent = "Link copied";
    announcer.textContent = "Shareable link copied to clipboard.";
    window.setTimeout(() => {
      label.textContent = "Copy link";
    }, 2200);
  } else {
    announcer.textContent = "Copy failed. You can copy the URL from your browser’s address bar.";
    label.textContent = "Copy failed";
    window.setTimeout(() => {
      label.textContent = "Copy link";
    }, 2200);
  }
}

document.addEventListener("click", (event) => {
  const link = event.target.closest("a");
  if (!link) return;

  if (link.hasAttribute("data-top")) {
    event.preventDefault();
    window.scrollTo({ top: 0, behavior: window.matchMedia("(prefers-reduced-motion: reduce)").matches ? "auto" : "smooth" });
    return;
  }

  if (link.hasAttribute("data-section")) {
    if (event.metaKey || event.ctrlKey || event.shiftKey || event.altKey) return;
    event.preventDefault();
    const section = link.dataset.section;
    if (routePath() === "/") {
      scrollToSection(section);
    } else {
      navigate("/", { section });
    }
    return;
  }

  if (!link.hasAttribute("data-link")) return;
  if (event.metaKey || event.ctrlKey || event.shiftKey || event.altKey || event.button !== 0) return;

  event.preventDefault();
  const href = link.getAttribute("href") || "#/";
  const nextPath = href.startsWith("#") ? href.slice(1) : href;
  navigate(nextPath);
});

document.addEventListener("click", (event) => {
  const filter = event.target.closest("[data-filter]");
  if (!filter) return;

  const topic = filter.dataset.filter;
  if (topic === "all") {
    if (routePath() === "/") {
      updateFilters("all", true);
    } else {
      navigate("/");
      requestAnimationFrame(() => updateFilters("all", true));
    }
    return;
  }

  const path = `/topics/${topic}`;
  if (routePath() === path) {
    updateFilters(topic, true);
  } else {
    navigate(path);
    requestAnimationFrame(() => updateFilters(topic, true));
  }
});

